/**
 * Get an icon by name
 * @param {string} name - Icon name
 * @param {object} options - Options like size, color, class
 * @returns {string} SVG string
 */
function getIcon(name, options = {}) {
  const icon = Icons[name];
  if (!icon) {
    console.warn(`Icon "${name}" not found`);
    return '';
  }
  
  let svg = icon;
  
  // Apply custom size
  if (options.size) {
    svg = svg.replace(/width="[^"]*"/, `width="${options.size}"`);
    svg = svg.replace(/height="[^"]*"/, `height="${options.size}"`);
  }
  
  // Apply custom class
  if (options.class) {
    svg = svg.replace(/<svg/, `<svg class="${options.class}"`);
  }
  
  // Apply custom color
  if (options.color) {
    svg = svg.replace(/stroke="[^"]*"/, `stroke="${options.color}"`);
    svg = svg.replace(/fill="[^"]*"/g, (match) => {
      if (match.includes('currentColor') || match.includes('none')) {
        return match;
      }
      return `fill="${options.color}"`;
    });
  }
  
  return svg;
}

/**
 * Get icon as HTML element
 * @param {string} name - Icon name
 * @param {object} options - Options
 * @returns {HTMLElement} SVG element
 */
function getIconElement(name, options = {}) {
  const svgString = getIcon(name, options);
  const wrapper = document.createElement('div');
  wrapper.innerHTML = svgString;
  return wrapper.firstElementChild;
}

/**
 * Replace icon placeholders in HTML
 * @param {HTMLElement} element - Container element
 */
function renderIcons(element = document) {
  const iconElements = element.querySelectorAll('[data-icon]');
  iconElements.forEach(el => {
    const iconName = el.dataset.icon;
    const options = {
      size: el.dataset.size || undefined,
      class: el.dataset.iconClass || undefined,
      color: el.dataset.color || undefined,
    };
    const icon = getIconElement(iconName, options);
    if (icon) {
      el.innerHTML = '';
      el.appendChild(icon);
    }
  });
}

